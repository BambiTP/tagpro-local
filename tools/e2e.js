// End-to-end smoke test against the local server: group -> launch -> joiner -> game.
const { io } = require('socket.io-client');
const base = process.argv[2] || 'http://localhost:3000';
let cookie = '';
const get = async (p, opt = {}) => { const r = await fetch(base + p, { redirect: 'manual', headers: { cookie }, ...opt }); const sc = r.headers.getSetCookie?.() || []; for (const c of sc) cookie = c.split(';')[0]; return r; };
const opts = (q) => ({ transports: ['websocket'], extraHeaders: { cookie }, query: q, reconnection: false });
(async () => {
  await get('/');
  const r = await get('/groups/create', { method: 'POST', headers: { cookie, 'content-type': 'application/x-www-form-urlencoded' }, body: 'name=Test&private=on' });
  const gid = r.headers.get('location').split('/').pop();
  console.log('group', gid);
  const g = io(base + '/groups/' + gid, opts({ group: gid }));
  const seen = [];
  g.onAny((ev, d) => seen.push(ev));
  await new Promise((res) => g.on('loaded', res));
  console.log('group events', [...new Set(seen)].join(','));
  g.emit('setting', { name: 'time', value: '1' });
  await new Promise((res) => setTimeout(res, 200));
  g.emit('groupPlay');
  await new Promise((res) => g.on('play', res));
  const j = io(base + '/games/find', opts({}));
  j.on('ready', () => j.emit('JoinerSelections', { regions: [], gameModes: ['classic'] }));
  const found = await new Promise((res) => j.on('FoundWorld', res));
  console.log('FoundWorld', found);
  const page = await (await get('/game')).text();
  const sock = page.match(/gameSocket = location.origin \+ "([^"]+)"/)[1];
  console.log('game socket', sock);
  const gs = io(base + sock, opts({}));
  const counts = {};
  let lastPos = null;
  gs.onAny((ev, d) => { counts[ev] = (counts[ev] || 0) + 1; if (ev === 'p') for (const u of (d.u || d)) if (u.rx != null) lastPos = [u.rx, u.ry, u.lx]; });
  gs.on('time', (t) => console.log('time', t));
  await new Promise((res) => setTimeout(res, 21500));
  console.log('pos at start', lastPos);
  gs.emit('keydown', { k: 'right', t: 1 });
  await new Promise((res) => setTimeout(res, 1500));
  gs.emit('keyup', { k: 'right', t: 2 });
  await new Promise((res) => setTimeout(res, 300));
  console.log('pos after holding right 1.5s', lastPos);
  console.log('event counts', counts);
  process.exit(0);
})().catch((e) => { console.error(e); process.exit(1); });
